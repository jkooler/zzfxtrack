import { getDefragmentedInstruments, getInstrumentMapping } from './instrument-manager.js';

/**
 * File Generator
 * Generates instruments.js file from instrument pool
 */

/**
 * Format a single instrument export
 * @param {Object} instrument - Instrument object
 * @returns {string} Formatted export line
 */
function formatInstrumentExport(instrument) {
    const paramsStr = JSON.stringify(instrument.params).replace(/"/g, '');
    return `export const ${instrument.exportName} = ${paramsStr};`;
}

/**
 * Generate complete instruments.js file content
 * @returns {string} File content
 */
export function generateInstrumentsFile() {
    const defragged = getDefragmentedInstruments();
    const mapping = getInstrumentMapping();
    
    const timestamp = new Date().toISOString();
    
    let content = `// instruments.js\n`;
    content += `// Auto-generated by Strudel to ZzFXM\n`;
    content += `// Last updated: ${timestamp}\n`;
    content += `//\n`;
    content += `// Waveform Indexes (Index 6):\n`;
    content += `// 0: Sine\n`;
    content += `// 1: Triangle\n`;
    content += `// 2: Sawtooth\n`;
    content += `// 3: Tangent\n`;
    content += `// 4: Noise\n`;
    content += `// 5: Square (Pulse)\n\n`;
    
    // Export individual instruments
    defragged.forEach(inst => {
        content += formatInstrumentExport(inst) + '\n';
    });
    
    content += '\n';
    
    // Export instrumentMapping
    content += `/**\n`;
    content += ` * Strudel Sound Names to ZzFXM Channel Indices\n`;
    content += ` * This mapping ensures we can use descriptive names in Strudel\n`;
    content += ` * while still baking to correct ZzFXM channels.\n`;
    content += ` */\n`;
    content += `export const instrumentMapping = {\n`;
    
    Object.entries(mapping).forEach(([alias, channel], index, arr) => {
        const comma = index < arr.length - 1 ? ',' : '';
        content += `    "${alias}": ${channel}${comma}\n`;
    });
    
    content += `};\n\n`;
    
    // Export instruments object
    content += `// Map them to IDs you want to use in Strudel\n`;
    content += `export const instruments = {\n`;
    
    defragged.forEach((inst, index, arr) => {
        const comma = index < arr.length - 1 ? ',' : '';
        content += `    "${inst.strudelAlias}": ${inst.exportName}${comma}\n`;
    });
    
    content += `};\n\n`;
    
    // Export instrumentArray
    content += `// Also export as array for the baker (ordered by channel index)\n`;
    content += `export const instrumentArray = [\n`;
    
    defragged.forEach((inst, index, arr) => {
        const comma = index < arr.length - 1 ? ',' : '';
        content += `    ${inst.exportName}${comma}\n`;
    });
    
    content += `];\n`;
    
    return content;
}

/**
 * Write instruments.js file to filesystem
 * Note: This uses the File System Access API which requires user permission
 * For now, we'll just return the content and let the user download it
 * @returns {string} File content
 */
export function writeInstrumentsFile() {
    const content = generateInstrumentsFile();
    
    // Create a blob and download link
    const blob = new Blob([content], { type: 'text/javascript' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'instruments.js';
    a.click();
    URL.revokeObjectURL(url);
    
    console.log('[FileGenerator] Generated instruments.js file');
    
    return content;
}

/**
 * Auto-update instruments.js file
 * This will be called whenever instruments change
 */
export async function autoUpdateInstrumentsFile() {
    const content = generateInstrumentsFile();
    
    // Store in sessionStorage for easy access
    sessionStorage.setItem('instruments-js-content', content);
    
    // Write to the actual file using the API
    try {
        const response = await fetch('/api/update-instruments', {
            method: 'POST',
            headers: {
                'Content-Type': 'text/javascript'
            },
            body: content
        });
        
        if (response.ok) {
            console.log('[FileGenerator] Successfully wrote instruments.js to file system');
        } else {
            console.warn('[FileGenerator] Failed to write instruments.js:', await response.text());
        }
    } catch (e) {
        console.warn('[FileGenerator] Could not write to file system (API not available):', e.message);
    }
    
    console.log('[FileGenerator] Auto-updated instruments.js content');
    
    return content;
}

/**
 * Get the current instruments.js content from sessionStorage
 * @returns {string|null} File content or null
 */
export function getCurrentInstrumentsContent() {
    return sessionStorage.getItem('instruments-js-content');
}
